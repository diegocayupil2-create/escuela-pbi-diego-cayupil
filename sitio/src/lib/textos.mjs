/** Singular o plural: plural(1, ['{n} capítulo', '{n} capítulos']) → «1 capítulo». */
export const plural = (n, [uno, varios]) => t(n === 1 ? uno : varios, { n });

/** Reemplaza {clave} por su valor. */
export const t = (texto, valores = {}) => texto.replace(/\{(\w+)\}/g, (m, k) => (k in valores ? String(valores[k]) : m));

/** Fecha AAAA-MM-DD como texto corto: 14-11-2026 en español y 2026-11-14 en inglés. */
export const fechaCorta = (fecha, lang) => (lang === 'es' ? fecha.split('-').reverse().join('-') : fecha);
